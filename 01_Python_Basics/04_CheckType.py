# Checking Data Types

a = 10
b = 3.14
c = "Hello"
d = True

print("Type of a:", type(a))
print("Type of b:", type(b))
print("Type of c:", type(c))
print("Type of d:", type(d))

# Type Conversion

# int to float
x = 10
y = float(x)
print("\nInteger:", x, "-> Float:", y)

# float to int
p = 7.89
q = int(p)
print("Float:", p, "-> Integer:", q)

# int to string
m = 25
n = str(m)
print("Integer:", m, "-> String:", n)

# string to int
s = "100"
t = int(s)
print("String:", s, "-> Integer:", t)

# string to float
u = "45.67"
v = float(u)
print("String:", u, "-> Float:", v)

# int to boolean
w = 1
z = bool(w)
print("Integer:", w, "-> Boolean:", z)