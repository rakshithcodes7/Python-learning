# ==========================================
# Python input() Function Examples
# ==========================================

# Taking string input
name = input("Enter your name: ")

print("\nString Input")
print("Name:", name)
print("Type:", type(name))

# Taking integer input
age = int(input("\nEnter your age: "))

print("\nInteger Input")
print("Age:", age)
print("Type:", type(age))

# Taking float input
salary = float(input("\nEnter your salary: "))

print("\nFloat Input")
print("Salary:", salary)
print("Type:", type(salary))

# Displaying all values
print("\nUser Details")
print("Name:", name)
print("Age:", age)
print("Salary:", salary)